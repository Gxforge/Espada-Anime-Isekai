export function getSwordEvolutionForLevel(level: number): SwordEvolutionTier {
  let current = SWORD_EVOLUTIONS[0];
  for (const tier of SWORD_EVOLUTIONS) {
    if (level >= tier.minLevel) {
      current = tier;
    }
  }
  return current;
}

export function getSwordTierById(id: SwordTierId): SwordEvolutionTier {
  return SWORD_EVOLUTIONS.find((t) => t.id === id) || SWORD_EVOLUTIONS[0];
}

export function getXpRequiredForLevel(level: number): number {
  // Smooth, fast early curve so Level 1 -> Level 5 (Copper) feels exciting and happens quickly!
  if (level <= 4) {
    return Math.round(35 + (level - 1) * 20);
  }
  if (level <= 10) {
    return Math.round(110 + (level - 4) * 38);
  }
  return Math.round(340 + Math.pow(level - 10, 1.35) * 65);
}

